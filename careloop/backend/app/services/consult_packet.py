"""Consult packet generator — compiles structured clinical handover packets for referrals."""

from __future__ import annotations

import json
from datetime import datetime
from typing import Any, Dict, List, Optional

from sqlalchemy.orm import Session

from app.core.clock import get_clock
from app.ai.provider import AIProvider
from app.ai.anthropic_provider import get_ai_provider
from app.db.models import Case, CaseEvent, Message, Patient, Provider, User


class ConsultPacketService:
    """Compiles structured consult and referral packets with audit trail."""

    def __init__(self, db: Session, ai_provider: Optional[AIProvider] = None):
        self.db = db
        self.clock = get_clock()
        self.ai = ai_provider or get_ai_provider()

    def generate_packet(
        self, case_id: str, requesting_user_id: str, include_ai_summary: bool = True
    ) -> Dict[str, Any]:
        """Assemble structured consult packet."""
        case = self.db.query(Case).filter(Case.id == case_id).one()
        patient = self.db.query(Patient).filter(Patient.id == case.patient_id).one()
        events = (
            self.db.query(CaseEvent)
            .filter(CaseEvent.case_id == case_id)
            .order_by(CaseEvent.seq.asc())
            .all()
        )
        messages = (
            self.db.query(Message)
            .filter(Message.case_id == case_id)
            .order_by(Message.sent_at.asc())
            .all()
        )

        # Minimum necessary identifiers
        patient_summary = {
            "patient_id": patient.id,
            "synthetic_name": patient.synthetic_name,
            "dob": patient.dob.isoformat(),
            "sex": patient.sex,
            "preferred_language": patient.language,
        }

        # Event timeline summary
        timeline = []
        for e in events:
            timeline.append({
                "seq": e.seq,
                "event_type": e.event_type,
                "from_state": e.from_state,
                "to_state": e.to_state,
                "occurred_at": e.occurred_at.isoformat(),
                "actor_role": e.actor_role,
            })

        # Contact attempts
        contact_attempts = []
        for m in messages:
            contact_attempts.append({
                "message_id": m.id,
                "channel": m.channel,
                "status": m.status.value if hasattr(m.status, "value") else str(m.status),
                "delivered_at": m.delivered_at.isoformat() if m.delivered_at else None,
            })

        # Deterministic result description based on pathway
        pathway_summaries = {
            "fit_positive_to_colonoscopy": "Actionable Bowel Screening FIT Positive result requiring diagnostic colonoscopy assessment.",
            "breast_recall": "Abnormal screening mammogram requiring diagnostic assessment and repeat imaging.",
            "cardiometabolic_hba1c": "Elevated HbA1c screening result requiring confirmatory testing and glycemic management plan.",
        }
        clinical_indication = pathway_summaries.get(
            case.pathway_id, f"Actionable screening finding on pathway: {case.pathway_id}"
        )

        ai_summary_text = None
        if include_ai_summary:
            ai_summary_text = self.ai.summarize_consult(
                case_events=timeline,
                clinical_notes=clinical_indication,
            )

        packet = {
            "packet_id": f"PKT-{case.id[:8]}",
            "generated_at": self.clock.now().isoformat(),
            "case_id": case.id,
            "pathway_id": case.pathway_id,
            "urgency_tier": case.urgency_tier,
            "current_state": case.current_state,
            "patient": patient_summary,
            "clinical_indication": clinical_indication,
            "timeline": timeline,
            "contact_attempts": contact_attempts,
            "ai_drafted_summary": ai_summary_text,
            "ai_review_status": "DRAFT_PENDING_CLINICAL_SIGN_OFF" if ai_summary_text else "N/A",
            "closure_evidence_required": ["colonoscopy_report", "histology_report"],
            "disclaimer": "SIMULATED DATA: NOT FOR CLINICAL USE. Consult packet generated by CareLoop prototype.",
        }
        return packet

